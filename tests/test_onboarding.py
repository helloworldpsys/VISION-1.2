def test_run_setup_records_downloaded_vosk_model(tmp_path: Path) -> None:
    env_file = tmp_path / ".env"
    model = tmp_path / "models" / "vosk-model-small-en-us-0.15"
    (model / "conf").mkdir(parents=True)
    (model / "am").mkdir()
    answers = iter(["Vision", "Taha", "llama3", "auto", "y"])
    run_setup(
        env_path=env_file,
        input_fn=lambda prompt: next(answers),
        platform=create_platform("linux", runner=lambda *a, **k: None, which=lambda n: None),
        body_probe=lambda host: OllamaProbe(True, ("llama3:latest",)),
        model_installer=lambda destination, url, sha256=None: model,
    )
    text = env_file.read_text(encoding="utf-8")
    assert f"VOSK_MODEL_PATH={model}" in text
    assert "PREFER_OFFLINE_STT=true" in text


