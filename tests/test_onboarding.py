class FakeResponse:
    def __init__(self, body: bytes, headers: dict[str, str] | None = None) -> None:
        self._buffer = io.BytesIO(body)
        self.headers = headers or {}

    def read(self, size: int = -1) -> bytes:
        return self._buffer.read(size)

    def __enter__(self) -> FakeResponse:
        return self

    def __exit__(self, *exc_info: object) -> bool:
        return False


def fake_opener(body: bytes, headers: dict[str, str] | None = None):
    def opener(url: str, timeout: float = 0) -> FakeResponse:
        return FakeResponse(body, headers)

    return opener


def build_model_zip() -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as bundle:
        bundle.writestr("vosk-model-small-en-us-0.15/conf/model.conf", "x")
        bundle.writestr("vosk-model-small-en-us-0.15/am/final.mdl", "x")
    return buffer.getvalue()


# ------------------------------------------------------------------- env file
def test_update_env_file_creates_file(tmp_path: Path) -> None:
    target = tmp_path / ".env"
    assert update_env_file(target, {"OLLAMA_MODEL": "llama3"}) is True
    text = target.read_text(encoding="utf-8")
    assert "OLLAMA_MODEL=llama3" in text
    assert "generated by" in text


def test_update_env_file_merges_without_touching_comments(tmp_path: Path) -> None:
    target = tmp_path / ".env"
    target.write_text("# keep me\nOLLAMA_MODEL=old\nCUSTOM=1\n", encoding="utf-8")
    assert update_env_file(target, {"OLLAMA_MODEL": "new", "TTS_ENGINE": "native"}) is True
    text = target.read_text(encoding="utf-8")
    assert "# keep me" in text
    assert "OLLAMA_MODEL=new" in text
    assert "CUSTOM=1" in text
    assert "TTS_ENGINE=native" in text


def test_update_env_file_noop_when_unchanged(tmp_path: Path) -> None:
    target = tmp_path / ".env"
    update_env_file(target, {"OLLAMA_MODEL": "llama3"})
    assert update_env_file(target, {"OLLAMA_MODEL": "llama3"}) is False


# --------------------------------------------------------------------- Ollama
def test_probe_ollama_returns_models() -> None:
    body = b'{"models": [{"name": "llama3:latest"}, {"name": "mistral:latest"}]}'
    probe = probe_ollama("http://127.0.0.1:11434", opener=fake_opener(body))
    assert probe.ok is True
    assert probe.models == ("llama3:latest", "mistral:latest")


def test_probe_ollama_reports_failure() -> None:
    def boom(url: str, timeout: float = 0):
        raise OSError("connection refused")

    probe = probe_ollama("http://127.0.0.1:11434", opener=boom)
    assert probe.ok is False
    assert "connection refused" in probe.error


def test_suggest_model_prefers_newest_llama() -> None:
    assert suggest_model(["mistral:latest", "llama3.2:1b"]) == "llama3.2:1b"
    assert suggest_model([]) == "llama3"


# ----------------------------------------------------------------- Vosk model
def test_download_vosk_model_verifies_checksum(tmp_path: Path) -> None:
    payload = build_model_zip()
    expected = hashlib.sha256(payload).hexdigest()
    model = download_vosk_model(
        tmp_path,
        "https://example.invalid/model.zip",
        sha256=expected,
        opener=fake_opener(payload, {"Content-Length": str(len(payload))}),
    )
    assert model.name == "vosk-model-small-en-us-0.15"
    assert (model / "conf").is_dir()


def test_download_vosk_model_rejects_bad_checksum(tmp_path: Path) -> None:
    with pytest.raises(SetupError, match="checksum mismatch"):
        download_vosk_model(
            tmp_path,
            "https://example.invalid/model.zip",
            sha256="0" * 64,
            opener=fake_opener(build_model_zip()),
        )
    assert list(tmp_path.iterdir()) == []


# --------------------------------------------------------------------- doctor
def fake_checks(*, ollama_ok: bool = True, mic_ok: bool = True) -> list[Check]:
    return [
        Check("python", True, "3.10.0", required=True),
        Check("ollama", ollama_ok, "probe", "Run `ollama serve`.", required=True),
        Check("microphone", mic_ok, "probe", "Use --text."),
    ]


def test_doctor_exit_code_ignores_optional_failures(capsys) -> None:
    code = format_checks(fake_checks(mic_ok=False))
    assert code == 0
    assert "microphone" in capsys.readouterr().out


def test_doctor_exit_code_fails_on_required(capsys) -> None:
    code = format_checks(fake_checks(ollama_ok=False))
    assert code == 1
    output = capsys.readouterr().out
    assert "ollama" in output
    assert "fix: Run `ollama serve`." in output


def test_collect_checks_marks_missing_ollama(tmp_path: Path) -> None:
    platform = create_platform("linux", runner=lambda *a, **k: None, which=lambda name: None)
    config = Config(data_dir=tmp_path, ollama_model="llama3").resolved_paths()
    checks = collect_checks(
        config,
        platform,
        env_path=tmp_path / ".env",
        model_available=lambda name: False,
        microphone_probe=lambda: (True, "fake mic"),
        camera_probe=lambda: (True, "fake camera"),
        ollama_probe=lambda host: OllamaProbe(False, (), "offline"),
    )
    by_name = {check.name: check for check in checks}
    assert by_name["ollama"].ok is False
    assert by_name["ollama"].required is True
    assert by_name["offline-stt"].ok is False
    assert by_name["config"].ok is False


