"""First-run setup wizard and capability doctor.

``python -m vision --setup`` writes a minimal ``.env`` after probing Ollama,
and ``python -m vision --doctor`` reports every hardware/network capability
with a fix hint.  Both are deliberately dependency-light so they still work
when OpenCV, MediaPipe or a microphone backend failed to install.
"""

